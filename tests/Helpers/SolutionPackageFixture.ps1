function New-TestCabinetBytes {
    <# Builds a cabinet without compression. A file is @{ Name; Content (bytes); Size (a declared size that differs from the content, optional); Utf8 (the name is UTF-8, optional) }. #>
    param ([System.Collections.IDictionary[]] $File, [System.UInt16] $Flags = 0, [System.Byte] $MajorVersion = 1)

    $latin1 = [System.Text.Encoding]::GetEncoding(28591)
    $table = New-Object -TypeName System.IO.MemoryStream
    $data = New-Object -TypeName System.IO.MemoryStream
    $tableWriter = New-Object -TypeName System.IO.BinaryWriter -ArgumentList $table
    foreach ($item in $File) {
        $content = [System.Byte[]]$item.Content
        $size = if ($item.Contains('Size')) { [System.UInt32]$item.Size } else { [System.UInt32]$content.Length }
        $tableWriter.Write([System.UInt32]$size)
        $tableWriter.Write([System.UInt32]$data.Length)
        $tableWriter.Write([System.UInt16]0)
        $tableWriter.Write([System.UInt16]0x5A21)
        $tableWriter.Write([System.UInt16]0x6000)
        if ($item.Contains('Utf8') -and $item.Utf8) {
            $tableWriter.Write([System.UInt16]0xA0)
            $tableWriter.Write([System.Text.Encoding]::UTF8.GetBytes([System.String]$item.Name))
        }
        else {
            $tableWriter.Write([System.UInt16]0x20)
            $tableWriter.Write($latin1.GetBytes([System.String]$item.Name))
        }
        $tableWriter.Write([System.Byte]0)
        $data.Write($content, 0, $content.Length)
    }
    $tableWriter.Flush()

    $filesOffset = 36 + 8
    $dataOffset = $filesOffset + $table.Length
    $total = $dataOffset + 8 + $data.Length
    $stream = New-Object -TypeName System.IO.MemoryStream
    $writer = New-Object -TypeName System.IO.BinaryWriter -ArgumentList $stream
    $writer.Write($latin1.GetBytes('MSCF'))
    $writer.Write([System.UInt32]0)
    $writer.Write([System.UInt32]$total)
    $writer.Write([System.UInt32]0)
    $writer.Write([System.UInt32]$filesOffset)
    $writer.Write([System.UInt32]0)
    $writer.Write([System.Byte]3)
    $writer.Write([System.Byte]$MajorVersion)
    $writer.Write([System.UInt16]1)
    $writer.Write([System.UInt16]$File.Count)
    $writer.Write([System.UInt16]$Flags)
    $writer.Write([System.UInt16]0)
    $writer.Write([System.UInt16]0)
    $writer.Write([System.UInt32]$dataOffset)
    $writer.Write([System.UInt16]1)
    $writer.Write([System.UInt16]0)
    $writer.Write($table.ToArray())
    $writer.Write([System.UInt32]0)
    $writer.Write([System.UInt16]$data.Length)
    $writer.Write([System.UInt16]$data.Length)
    $writer.Write($data.ToArray())
    $writer.Flush()
    return , $stream.ToArray()
}

function New-TestCabinet {
    <# Builds a real cabinet (MSZIP) from a folder with makecab on Windows, or gcab elsewhere. Returns $false when there is no tool, and throws when makecab fails. #>
    param ([System.String] $SourceFolder, [System.String] $Path)

    $sourceFull = [System.IO.Path]::GetFullPath($SourceFolder).TrimEnd('\', '/')
    $files = @(Get-ChildItem -LiteralPath $SourceFolder -Recurse -File | Sort-Object -Property FullName)
    if ([System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT) {
        $makecab = Join-Path -Path ([System.Environment]::SystemDirectory) -ChildPath 'makecab.exe'
        if (-not (Test-Path -LiteralPath $makecab)) {
            return $false
        }
        $directory = Split-Path -Path $Path -Parent
        $directive = [System.Collections.Generic.List[string]]::new()
        foreach ($line in @('.OPTION EXPLICIT', ".Set CabinetNameTemplate=$([System.IO.Path]::GetFileName($Path))", ".Set DiskDirectoryTemplate=$directory",
                '.Set Cabinet=on', '.Set Compress=on', '.Set CompressionType=MSZIP', '.Set MaxDiskSize=0', '.Set InfFileName=NUL', '.Set RptFileName=NUL')) {
            $directive.Add($line)
        }
        # The files at the root come first, before any destination directory is set.
        foreach ($file in @($files | Where-Object { $_.DirectoryName.TrimEnd('\', '/') -eq $sourceFull })) {
            $directive.Add(('"{0}" "{1}"' -f $file.FullName, $file.Name))
        }
        foreach ($file in @($files | Where-Object { $_.DirectoryName.TrimEnd('\', '/') -ne $sourceFull })) {
            $relative = $file.FullName.Substring($sourceFull.Length + 1)
            $directive.Add(".Set DestinationDir=$(Split-Path -Path $relative -Parent)")
            $directive.Add(('"{0}" "{1}"' -f $file.FullName, $file.Name))
        }
        $ddf = Join-Path -Path $directory -ChildPath 'package.ddf'
        Set-Content -LiteralPath $ddf -Value $directive -Encoding Ascii
        $previous = $ErrorActionPreference
        $ErrorActionPreference = 'Continue'
        try {
            $output = (& $makecab '/F' $ddf 2>&1 | ForEach-Object { [System.String]$_ }) -join ' '
        }
        finally {
            $ErrorActionPreference = $previous
        }
        if (-not (Test-Path -LiteralPath $Path)) {
            throw "makecab did not build the cabinet (exit code $LASTEXITCODE): $output"
        }
        return $true
    }

    $gcab = Get-Command -Name 'gcab' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($null -eq $gcab) {
        return $false
    }
    $relativeName = @($files | ForEach-Object { $_.FullName.Substring($sourceFull.Length + 1) })
    Push-Location -LiteralPath $SourceFolder
    try {
        $null = & $gcab.Source '-c' '-z' $Path @relativeName 2>&1
    }
    finally {
        Pop-Location
    }
    return (Test-Path -LiteralPath $Path)
}
