function Export-SPSInventoryReport {
    <#
        .SYNOPSIS
        Exports the scored inventory and report-pack JSON artifacts.

        .DESCRIPTION
        Writes the consolidated inventory (site records plus any web-application
        enumeration failure records, including complexity category and score where
        available) to three files in the output folder (created when missing):

        - a CSV file for review in Excel;
        - a JSON file for downstream automation (for example feeding migration wave
          planning);
        - a self-contained HTML report (Aptos style, category summary box) for sharing
          with stakeholders without any external tooling.

        Also writes a modular JSON report pack and a manifest file so downstream
        automation and dashboards can consume focused datasets without parsing one
        large payload:

        - `*-sites-*.json`
        - `*-auth-*.json`
        - `*-workflows-*.json`
        - `*-irm-locks-*.json`
        - `*-large-content-*.json`
        - `*-alerts-*.json`
        - `*-manifest-*.json`

        Returns a PSCustomObject with the output paths.

        .PARAMETER InputObject
        The scored inventory records to export.

        .PARAMETER OutputFolder
        Folder where the CSV, JSON and HTML files are written.

        .PARAMETER BaseName
        Base file name (without extension). Defaults to 'SPSSiteInventory'. A timestamp
        is appended to keep successive runs side by side.

        .PARAMETER EnvName
        Optional environment identifier shown in the HTML report header (for example
        'PROD').

        .PARAMETER SolutionMap
        Optional farm-solution (WSP) records (from Get-SPSFarmSolutionMap). When provided,
        the HTML report includes a "Farm solutions (WSP)" section.

        .PARAMETER ContentTypes
        Optional content-type definitions and list bindings collected with the site
        signals. When supplied, adds a content-type HTML section and dedicated
        -contenttypes CSV/JSON files, including valid empty reports.

        .PARAMETER SolutionJsonPath
        Optional path to the solutions JSON report generated by Export-SPSSolutionReport.
        When provided, this path is referenced from the report-pack manifest.

        .EXAMPLE
        Export-SPSInventoryReport -InputObject $scored -OutputFolder C:\Inventory
    #>
    [CmdletBinding()]
    [OutputType([System.Management.Automation.PSCustomObject])]
    param
    (
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Object[]]
        $InputObject,

        [Parameter(Mandatory = $true)]
        [System.String]
        $OutputFolder,

        [Parameter()]
        [System.String]
        $BaseName = 'SPSSiteInventory',

        [Parameter()]
        [System.String]
        $EnvName = '',

        [Parameter()]
        [AllowEmptyCollection()]
        [AllowNull()]
        [System.Object[]]
        $SolutionMap = @(),

        [Parameter()]
        [AllowEmptyCollection()]
        [System.Object[]]
        $ContentTypes = @(),

        [Parameter()]
        [System.String]
        $SolutionJsonPath = ''
    )

    if (-not (Test-Path -Path $OutputFolder)) {
        $null = New-Item -Path $OutputFolder -ItemType Directory -Force
    }

    $timestamp = Get-Date -Format 'yyyyMMdd-HHmm'
    $csvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-{1}.csv' -f $BaseName, $timestamp)
    $jsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-{1}.json' -f $BaseName, $timestamp)
    $htmlPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-{1}.html' -f $BaseName, $timestamp)
    $sitesJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-sites-{1}.json' -f $BaseName, $timestamp)
    $authJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-auth-{1}.json' -f $BaseName, $timestamp)
    $workflowsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-workflows-{1}.json' -f $BaseName, $timestamp)
    $irmLocksJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-irm-locks-{1}.json' -f $BaseName, $timestamp)
    $largeContentJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-large-content-{1}.json' -f $BaseName, $timestamp)
    $alertsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-alerts-{1}.json' -f $BaseName, $timestamp)
    $manifestJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-manifest-{1}.json' -f $BaseName, $timestamp)

    $InputObject | Export-Csv -Path $csvPath -NoTypeInformation -Encoding UTF8
    ConvertTo-Json -InputObject @($InputObject) -Depth 6 | Set-Content -Path $jsonPath -Encoding UTF8

    $records = @($InputObject)
    $siteRecords = @($records | Where-Object { $_.InventoryScope -ne 'WebApplication' })
    $authRecords = @(
        foreach ($group in ($records | Where-Object { $_.AuthenticationZones } | Group-Object -Property WebAppUrl, AuthenticationZones)) {
            $first = $group.Group[0]
            [PSCustomObject]@{
                WebAppUrl = $first.WebAppUrl
                AuthenticationModes = $first.AuthenticationModes
                AuthenticationZones = $first.AuthenticationZones
                FbaMembershipProviders = $first.FbaMembershipProviders
                FbaRoleProviders = $first.FbaRoleProviders
                HasFbaZone = $first.HasFbaZone
                AuthenticationReviewRequired = $first.AuthenticationReviewRequired
                SiteCollectionCount = @($group.Group | Where-Object { $_.InventoryScope -ne 'WebApplication' }).Count
            }
        }
    )
    $workflowRecords = @(
        foreach ($record in $siteRecords) {
            [PSCustomObject]@{
                Url = $record.Url
                WebApp = $record.WebApp
                AssessmentStatus = $record.AssessmentStatus
                Category = $record.Category
                Workflow2010Count = $record.Workflow2010Count
                Workflow2013Count = $record.Workflow2013Count
            }
        }
    )
    $irmLockRecords = @(
        foreach ($record in $siteRecords) {
            [PSCustomObject]@{
                Url = $record.Url
                WebApp = $record.WebApp
                AssessmentStatus = $record.AssessmentStatus
                SiteLockState = $record.SiteLockState
                IsLockedSite = $record.IsLockedSite
                IrmEnabledListCount = $record.IrmEnabledListCount
            }
        }
    )
    $largeContentRecords = @(
        foreach ($record in $siteRecords) {
            [PSCustomObject]@{
                Url = $record.Url
                WebApp = $record.WebApp
                AssessmentStatus = $record.AssessmentStatus
                IsLargeSite = $record.IsLargeSite
                LargeListCount = $record.LargeListCount
                LargeListExamples = $record.LargeListExamples
                LargeListViewCount = $record.LargeListViewCount
                LargeListViewExamples = $record.LargeListViewExamples
                CheckedOutFileCount = $record.CheckedOutFileCount
                CheckedOutFileExamples = $record.CheckedOutFileExamples
                FileVersionCount = $record.FileVersionCount
                FileVersionExamples = $record.FileVersionExamples
            }
        }
    )

    $alerts = [System.Collections.Generic.List[object]]::new()
    foreach ($record in $records) {
        $scope = if ($null -ne $record.PSObject.Properties['InventoryScope']) { [string]$record.InventoryScope } else { 'SiteCollection' }
        if ($scope -eq 'WebApplication') {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'WebApplicationEnumerationFailed'
                    Severity = 'High'
                    Url = if ($record.WebAppUrl) { $record.WebAppUrl } else { $record.Url }
                    Value = if ($record.SiteInventoryWarnings) { $record.SiteInventoryWarnings } else { $record.AssessmentWarnings }
                    Message = 'Site collection enumeration failed for this web application.'
                })
        }
        if ($record.AssessmentStatus -eq 'Failed') {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'AssessmentFailed'
                    Severity = 'High'
                    Url = $record.Url
                    Value = $record.AssessmentWarnings
                    Message = 'Site assessment failed.'
                })
        }
        if ($record.AssessmentStatus -eq 'Partial') {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'AssessmentPartial'
                    Severity = 'Medium'
                    Url = $record.Url
                    Value = $record.AssessmentWarnings
                    Message = 'Site assessment is partial and may miss signals.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [int]$record.Workflow2010Count -gt 0) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'Workflow2010'
                    Severity = 'High'
                    Url = $record.Url
                    Value = [int]$record.Workflow2010Count
                    Message = 'Legacy SharePoint 2010 workflows require migration remediation.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [int]$record.InfoPathFormCount -gt 0) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'InfoPath'
                    Severity = 'High'
                    Url = $record.Url
                    Value = [int]$record.InfoPathFormCount
                    Message = 'InfoPath forms are not supported in SharePoint Online.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [bool]$record.UsesFullTrustCode) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'FullTrustCode'
                    Severity = 'High'
                    Url = $record.Url
                    Value = $true
                    Message = 'Custom full-trust code is a migration blocker.'
                })
        }
        if ([bool]$record.HasFbaZone) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'FbaConfigured'
                    Severity = 'High'
                    Url = $record.Url
                    Value = $true
                    Message = 'Forms-based authentication requires identity remediation.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [bool]$record.IsLockedSite) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'LockedSite'
                    Severity = 'High'
                    Url = $record.Url
                    Value = $record.SiteLockState
                    Message = 'Site lock state blocks or delays migration.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [int]$record.IrmEnabledListCount -gt 0) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'IrmEnabledLists'
                    Severity = 'High'
                    Url = $record.Url
                    Value = [int]$record.IrmEnabledListCount
                    Message = 'IRM-enabled lists require records-protection remediation.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [bool]$record.IsLargeSite) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'LargeSite'
                    Severity = 'Medium'
                    Url = $record.Url
                    Value = $record.SizeGB
                    Message = 'Site content size is above the configured large-site threshold.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [int]$record.LargeListCount -gt 0) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'LargeLists'
                    Severity = 'Medium'
                    Url = $record.Url
                    Value = [int]$record.LargeListCount
                    Message = 'Large lists were detected and may require migration batching or cleanup.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [int]$record.LargeListViewCount -gt 0) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'LargeListViews'
                    Severity = 'Medium'
                    Url = $record.Url
                    Value = [int]$record.LargeListViewCount
                    Message = 'Large-list views were detected and should be reviewed for migration readiness.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [int]$record.CheckedOutFileCount -gt 0) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'CheckedOutFiles'
                    Severity = 'Medium'
                    Url = $record.Url
                    Value = [int]$record.CheckedOutFileCount
                    Message = 'Checked-out files were detected and should be checked in before migration.'
                })
        }
        if ($scope -eq 'SiteCollection' -and [int]$record.FileVersionCount -gt 0) {
            $alerts.Add([PSCustomObject]@{
                    AlertType = 'FileVersions'
                    Severity = 'Medium'
                    Url = $record.Url
                    Value = [int]$record.FileVersionCount
                    Message = 'Files with high version counts were detected and may increase migration time.'
                })
        }
    }

    ConvertTo-Json -InputObject @($records) -Depth 6 | Set-Content -Path $sitesJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($authRecords) -Depth 6 | Set-Content -Path $authJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($workflowRecords) -Depth 6 | Set-Content -Path $workflowsJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($irmLockRecords) -Depth 6 | Set-Content -Path $irmLocksJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($largeContentRecords) -Depth 6 | Set-Content -Path $largeContentJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($alerts.ToArray()) -Depth 6 | Set-Content -Path $alertsJsonPath -Encoding UTF8

    $htmlParams = @{
        InputObject = @($InputObject)
        EnvName = $EnvName
        SolutionMap = @($SolutionMap)
    }
    $contentTypesCsvPath = $null
    $contentTypesJsonPath = $null
    if ($PSBoundParameters.ContainsKey('ContentTypes')) {
        $htmlParams['ContentTypes'] = @($ContentTypes)
        $contentTypesCsvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-contenttypes-{1}.csv' -f $BaseName, $timestamp)
        $contentTypesJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-contenttypes-{1}.json' -f $BaseName, $timestamp)
        $columns = @(
            'SiteUrl', 'WebUrl', 'Scope', 'ListTitle', 'ListUrl', 'ContentTypeId', 'Name',
            'Group', 'ParentContentTypeId', 'FieldCount', 'FieldTypes',
            'DocumentTemplateUrl', 'Hidden', 'ReadOnly', 'Sealed'
        )
        if ($ContentTypes.Count -gt 0) {
            $ContentTypes | Select-Object -Property $columns |
                Export-Csv -Path $contentTypesCsvPath -NoTypeInformation -Encoding UTF8
        }
        else {
            Set-Content -Path $contentTypesCsvPath -Value ('"' + ($columns -join '","') + '"') -Encoding UTF8
        }
        ConvertTo-Json -InputObject @($ContentTypes) -Depth 6 |
            Set-Content -Path $contentTypesJsonPath -Encoding UTF8
    }

    $html = ConvertTo-SPSInventoryHtml @htmlParams
    $html | Set-Content -Path $htmlPath -Encoding UTF8

    $totalSizeGb = 0.0
    foreach ($record in $siteRecords) {
        if ($null -ne $record.SizeGB) {
            try {
                $totalSizeGb += [double]$record.SizeGB
            }
            catch {
                continue
            }
        }
    }

    $manifest = [PSCustomObject]@{
        ReportPackVersion = '1.0'
        GeneratedOn = (Get-Date).ToString('o')
        BaseName = $BaseName
        Timestamp = $timestamp
        Summary = [PSCustomObject]@{
            TotalRecords = @($records).Count
            SiteCollections = @($siteRecords).Count
            WebApplicationFailures = @($records | Where-Object { $_.InventoryScope -eq 'WebApplication' }).Count
            PartialAssessments = @($siteRecords | Where-Object { $_.AssessmentStatus -eq 'Partial' }).Count
            FailedAssessments = @($siteRecords | Where-Object { $_.AssessmentStatus -eq 'Failed' }).Count
            TotalContentGB = [math]::Round($totalSizeGb, 2)
            AlertCount = @($alerts).Count
        }
        Files = [PSCustomObject]@{
            InventoryCsv = $csvPath
            InventoryJson = $jsonPath
            InventoryHtml = $htmlPath
            SitesJson = $sitesJsonPath
            AuthJson = $authJsonPath
            WorkflowsJson = $workflowsJsonPath
            IrmLocksJson = $irmLocksJsonPath
            LargeContentJson = $largeContentJsonPath
            AlertsJson = $alertsJsonPath
            ContentTypesCsv = $contentTypesCsvPath
            ContentTypesJson = $contentTypesJsonPath
            SolutionsJson = if ($SolutionJsonPath) { $SolutionJsonPath } else { $null }
        }
    }
    ConvertTo-Json -InputObject $manifest -Depth 6 | Set-Content -Path $manifestJsonPath -Encoding UTF8

    return [PSCustomObject]@{
        CsvPath  = $csvPath
        JsonPath = $jsonPath
        HtmlPath = $htmlPath
        SitesJsonPath = $sitesJsonPath
        AuthJsonPath = $authJsonPath
        WorkflowsJsonPath = $workflowsJsonPath
        IrmLocksJsonPath = $irmLocksJsonPath
        LargeContentJsonPath = $largeContentJsonPath
        AlertsJsonPath = $alertsJsonPath
        ManifestJsonPath = $manifestJsonPath
        ContentTypesCsvPath = $contentTypesCsvPath
        ContentTypesJsonPath = $contentTypesJsonPath
    }
}
