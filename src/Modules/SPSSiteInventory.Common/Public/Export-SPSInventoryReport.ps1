function Export-SPSInventoryReport {
    <#
        .SYNOPSIS
        Exports the scored inventory and report-pack JSON artifacts.

        .DESCRIPTION
        Writes the consolidated inventory (site records plus any web-application
        enumeration failure records, including complexity category and score where
        available) to three files in the output folder (created when missing):

        - a CSV file for review in Excel;
        - a JSON file for downstream automation (for example feeding migration wave
          planning);
        - a self-contained HTML report (Aptos style, category summary box) for sharing
          with stakeholders without any external tooling.

        When managed metadata rows are supplied it also writes a per-list CSV and JSON
        file (`*-managedmetadata-*`) that follows the SMAT Managed Metadata Columns report.
        External list rows add `*-externallists-*` (SMAT External List report) and BCS
        application rows add `*-bcs-*` (SMAT BCS report), each as CSV and JSON. SharePoint
        alert rows (the "Alert Me" subscriptions of the users) add `*-sharepointalerts-*`
        (SMAT Alerts report), as CSV and JSON too. They are not the risk alerts below, and
        they hold the login names of the alert owners, so they stay out of the HTML report.

        Also writes a modular JSON report pack and a manifest file so downstream
        automation and dashboards can consume focused datasets without parsing one
        large payload:

        - `*-sites-*.json`
        - `*-auth-*.json`
        - `*-workflows-*.json`
        - `*-apps-*.json`
        - `*-publishing-*.json`
        - `*-permissions-*.json`
        - `*-irm-locks-*.json`
        - `*-large-content-*.json`
        - `*-alerts-*.json` (also written as `*-alerts-*.csv` for Excel)
        - `*-manifest-*.json`

        Every alert carries its severity, an explanation and a remediation hint taken from
        the alert catalog, so the alerts files and the HTML alerts section tell the reader
        what to do next.

        Returns a PSCustomObject with the output paths.

        .PARAMETER InputObject
        The scored inventory records to export.

        .PARAMETER OutputFolder
        Folder where the CSV, JSON and HTML files are written.

        .PARAMETER BaseName
        Base file name (without extension). Defaults to 'SPSSiteInventory'. A timestamp
        is appended to keep successive runs side by side.

        .PARAMETER EnvName
        Optional environment identifier shown in the HTML report header (for example
        'PROD').

        .PARAMETER SolutionMap
        Optional farm-solution (WSP) records (from Get-SPSFarmSolutionMap). When provided,
        the HTML report includes a "Farm solutions (WSP)" section.

        .PARAMETER ContentTypes
        Optional content-type definitions and list bindings collected with the site
        signals. When supplied, adds a content-type HTML section and dedicated
        -contenttypes CSV/JSON files, including valid empty reports.

        .PARAMETER ManagedMetadataLists
        Optional per-list managed metadata rows collected with the site signals (one row
        per list with managed metadata columns). When supplied, adds a managed metadata
        HTML section and dedicated -managedmetadata CSV/JSON files, including valid empty
        reports.

        .PARAMETER ExternalLists
        Optional per-list external list rows collected with the site signals (one row per
        list backed by a Business Connectivity Services external content type). When
        supplied, adds an external list HTML section and dedicated -externallists
        CSV/JSON files, including valid empty reports.

        .PARAMETER SharePointAlerts
        Optional per-alert rows collected with the site signals (the "Alert Me"
        subscriptions of the users, one row per alert). When supplied, adds dedicated
        -sharepointalerts CSV/JSON files, including valid empty reports. The rows include
        the login name of the alert owner, which is personal data.

        .PARAMETER BcsApplications
        Optional Business Connectivity Services LOB system rows from Get-SPSBcsApplication.
        When supplied, adds a BCS HTML section and dedicated -bcs CSV/JSON files, including
        valid empty reports.

        .PARAMETER BcsInventoryComplete
        Whether the BCS inventory could be read in full. Defaults to true. When false, the
        BCS section, the manifest and the alerts say that BCS applications may be missing.

        .PARAMETER SolutionJsonPath
        Optional path to the solutions JSON report generated by Export-SPSSolutionReport.
        When provided, this path is referenced from the report-pack manifest.

        .PARAMETER ExcludedPersonalSiteCount
        Number of personal sites that the scan left out (Scope.IncludePersonalSites). Shown in
        the HTML summary when above 0 and written to the manifest as ExcludedPersonalSites.

        .PARAMETER ExcludedSiteMasterCount
        Number of site masters that the scan left out (Scope.IncludeSiteMasters). Shown in
        the HTML summary when above 0 and written to the manifest as ExcludedSiteMasters.

        .EXAMPLE
        Export-SPSInventoryReport -InputObject $scored -OutputFolder C:\Inventory
    #>
    [CmdletBinding()]
    [OutputType([System.Management.Automation.PSCustomObject])]
    param
    (
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Object[]]
        $InputObject,

        [Parameter(Mandatory = $true)]
        [System.String]
        $OutputFolder,

        [Parameter()]
        [System.String]
        $BaseName = 'SPSSiteInventory',

        [Parameter()]
        [System.String]
        $EnvName = '',

        [Parameter()]
        [AllowEmptyCollection()]
        [AllowNull()]
        [System.Object[]]
        $SolutionMap = @(),

        [Parameter()]
        [AllowEmptyCollection()]
        [System.Object[]]
        $ContentTypes = @(),

        [Parameter()]
        [AllowEmptyCollection()]
        [System.Object[]]
        $ManagedMetadataLists = @(),

        [Parameter()]
        [AllowEmptyCollection()]
        [System.Object[]]
        $ExternalLists = @(),

        [Parameter()]
        [AllowEmptyCollection()]
        [System.Object[]]
        $SharePointAlerts = @(),

        [Parameter()]
        [AllowEmptyCollection()]
        [System.Object[]]
        $BcsApplications = @(),

        [Parameter()]
        [System.Boolean]
        $BcsInventoryComplete = $true,

        [Parameter()]
        [System.String]
        $SolutionJsonPath = '',

        [Parameter()]
        [System.Int32]
        $ExcludedPersonalSiteCount = 0,

        [Parameter()]
        [System.Int32]
        $ExcludedSiteMasterCount = 0
    )

    if (-not (Test-Path -Path $OutputFolder)) {
        $null = New-Item -Path $OutputFolder -ItemType Directory -Force
    }

    $timestamp = Get-Date -Format 'yyyyMMdd-HHmm'
    $csvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-{1}.csv' -f $BaseName, $timestamp)
    $jsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-{1}.json' -f $BaseName, $timestamp)
    $htmlPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-{1}.html' -f $BaseName, $timestamp)
    $sitesJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-sites-{1}.json' -f $BaseName, $timestamp)
    $authJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-auth-{1}.json' -f $BaseName, $timestamp)
    $workflowsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-workflows-{1}.json' -f $BaseName, $timestamp)
    $appsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-apps-{1}.json' -f $BaseName, $timestamp)
    $publishingJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-publishing-{1}.json' -f $BaseName, $timestamp)
    $permissionsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-permissions-{1}.json' -f $BaseName, $timestamp)
    $irmLocksJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-irm-locks-{1}.json' -f $BaseName, $timestamp)
    $largeContentJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-large-content-{1}.json' -f $BaseName, $timestamp)
    $alertsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-alerts-{1}.json' -f $BaseName, $timestamp)
    $alertsCsvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-alerts-{1}.csv' -f $BaseName, $timestamp)
    $manifestJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-manifest-{1}.json' -f $BaseName, $timestamp)

    $InputObject | ConvertTo-SPSCsvSafeRecord | Export-Csv -Path $csvPath -NoTypeInformation -Encoding UTF8
    ConvertTo-Json -InputObject @($InputObject) -Depth 6 | Set-Content -Path $jsonPath -Encoding UTF8

    $records = @($InputObject)
    $siteRecords = @($records | Where-Object { $_.InventoryScope -ne 'WebApplication' })
    $authRecords = @(
        foreach ($group in ($records | Where-Object { $_.AuthenticationZones } | Group-Object -Property WebAppUrl, AuthenticationZones)) {
            $first = $group.Group[0]
            [PSCustomObject]@{
                WebAppUrl = $first.WebAppUrl
                AuthenticationModes = $first.AuthenticationModes
                AuthenticationZones = $first.AuthenticationZones
                FbaMembershipProviders = $first.FbaMembershipProviders
                FbaRoleProviders = $first.FbaRoleProviders
                HasFbaZone = $first.HasFbaZone
                AuthenticationReviewRequired = $first.AuthenticationReviewRequired
                SiteCollectionCount = @($group.Group | Where-Object { $_.InventoryScope -ne 'WebApplication' }).Count
            }
        }
    )
    $workflowRecords = @(
        foreach ($record in $siteRecords) {
            [PSCustomObject]@{
                Url = $record.Url
                WebApp = $record.WebApp
                AssessmentStatus = $record.AssessmentStatus
                Category = $record.Category
                Workflow2010Count = $record.Workflow2010Count
                Workflow2010RunningInstanceCount = $record.Workflow2010RunningInstanceCount
                Workflow2013Count = $record.Workflow2013Count
                Workflow2013RunningInstanceCount = $record.Workflow2013RunningInstanceCount
                IsUnsupportedSiteTemplate = $record.IsUnsupportedSiteTemplate
                TemplateCompatibility = $record.TemplateCompatibility
                TemplateLanguageLcid = $record.TemplateLanguageLcid
                TemplateLanguageTag = $record.TemplateLanguageTag
                TemplateLanguageReviewRequired = $record.TemplateLanguageReviewRequired
            }
        }
    )
    $irmLockRecords = @(
        foreach ($record in $siteRecords) {
            [PSCustomObject]@{
                Url = $record.Url
                WebApp = $record.WebApp
                AssessmentStatus = $record.AssessmentStatus
                SiteLockState = $record.SiteLockState
                IsLockedSite = $record.IsLockedSite
                HasNoAccessLock = $record.HasNoAccessLock
                IrmEnabledListCount = $record.IrmEnabledListCount
            }
        }
    )
    $appRecords = @(
        foreach ($record in $siteRecords) {
            [PSCustomObject]@{
                Url = $record.Url
                WebApp = $record.WebApp
                AssessmentStatus = $record.AssessmentStatus
                Category = $record.Category
                AppInstanceCount = $record.AppInstanceCount
                AppWebCount = $record.AppWebCount
                AppInstanceExamples = $record.AppInstanceExamples
            }
        }
    )
    $publishingRecords = @(
        foreach ($record in $siteRecords) {
            [PSCustomObject]@{
                Url = $record.Url
                WebApp = $record.WebApp
                AssessmentStatus = $record.AssessmentStatus
                Category = $record.Category
                PublishingInfrastructureEnabled = $record.PublishingInfrastructureEnabled
                PublishingWebCount = $record.PublishingWebCount
                PublishingPageCount = $record.PublishingPageCount
                PublishingPageLayoutCount = $record.PublishingPageLayoutCount
                PublishingPageLayoutExamples = $record.PublishingPageLayoutExamples
                CustomizedPageCount = $record.CustomizedPageCount
                CustomizedPageExamples = $record.CustomizedPageExamples
            }
        }
    )
    # Includes web application failure rows: they retain the policy values read for that application.
    $permissionRecords = @(
        foreach ($record in $records) {
            [PSCustomObject]@{
                InventoryScope = $record.InventoryScope
                Url = $record.Url
                WebApp = $record.WebApp
                WebAppUrl = $record.WebAppUrl
                AssessmentStatus = $record.AssessmentStatus
                Category = $record.Category
                BrowserFileHandling = $record.BrowserFileHandling
                WebAppPolicyCount = $record.WebAppPolicyCount
                WebAppPolicyExamples = $record.WebAppPolicyExamples
                CustomPermissionLevelCount = $record.CustomPermissionLevelCount
                CustomPermissionLevelExamples = $record.CustomPermissionLevelExamples
                EmailEnabledListCount = $record.EmailEnabledListCount
                EmailEnabledListExamples = $record.EmailEnabledListExamples
                HtmlFileCount = $record.HtmlFileCount
                HtmlFileExamples = $record.HtmlFileExamples
            }
        }
    )
    $largeContentRecords = @(
        foreach ($record in $siteRecords) {
            [PSCustomObject]@{
                Url = $record.Url
                WebApp = $record.WebApp
                AssessmentStatus = $record.AssessmentStatus
                IsLargeSite = $record.IsLargeSite
                LargeListCount = $record.LargeListCount
                LargeListExamples = $record.LargeListExamples
                LargeListViewCount = $record.LargeListViewCount
                LargeListViewExamples = $record.LargeListViewExamples
                CheckedOutFileCount = $record.CheckedOutFileCount
                CheckedOutFileExamples = $record.CheckedOutFileExamples
                FileVersionCount = $record.FileVersionCount
                FileVersionExamples = $record.FileVersionExamples
            }
        }
    )

    $alertParams = @{ InputObject = @($records) }
    if ($PSBoundParameters.ContainsKey('BcsApplications')) {
        $alertParams['BcsApplication'] = @($BcsApplications)
        $alertParams['BcsInventoryComplete'] = $BcsInventoryComplete
    }
    $alerts = @(Get-SPSInventoryAlert @alertParams)

    ConvertTo-Json -InputObject @($records) -Depth 6 | Set-Content -Path $sitesJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($authRecords) -Depth 6 | Set-Content -Path $authJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($workflowRecords) -Depth 6 | Set-Content -Path $workflowsJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($appRecords) -Depth 6 | Set-Content -Path $appsJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($publishingRecords) -Depth 6 | Set-Content -Path $publishingJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($permissionRecords) -Depth 6 | Set-Content -Path $permissionsJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($irmLockRecords) -Depth 6 | Set-Content -Path $irmLocksJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($largeContentRecords) -Depth 6 | Set-Content -Path $largeContentJsonPath -Encoding UTF8
    ConvertTo-Json -InputObject @($alerts) -Depth 6 | Set-Content -Path $alertsJsonPath -Encoding UTF8
    $alertColumns = @('AlertType', 'Severity', 'Url', 'Value', 'Message', 'Remediation', 'Reference')
    if ($alerts.Count -gt 0) {
        $alerts | Select-Object -Property $alertColumns |
            ConvertTo-SPSCsvSafeRecord |
            Export-Csv -Path $alertsCsvPath -NoTypeInformation -Encoding UTF8
    }
    else {
        Set-Content -Path $alertsCsvPath -Value ('"' + ($alertColumns -join '","') + '"') -Encoding UTF8
    }

    $htmlParams = @{
        InputObject = @($InputObject)
        EnvName = $EnvName
        SolutionMap = @($SolutionMap)
        Alert = @($alerts)
        ExcludedPersonalSiteCount = $ExcludedPersonalSiteCount
        ExcludedSiteMasterCount = $ExcludedSiteMasterCount
    }
    $contentTypesCsvPath = $null
    $contentTypesJsonPath = $null
    if ($PSBoundParameters.ContainsKey('ContentTypes')) {
        $htmlParams['ContentTypes'] = @($ContentTypes)
        $contentTypesCsvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-contenttypes-{1}.csv' -f $BaseName, $timestamp)
        $contentTypesJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-contenttypes-{1}.json' -f $BaseName, $timestamp)
        $columns = @(
            'SiteUrl', 'WebUrl', 'Scope', 'ListTitle', 'ListUrl', 'ContentTypeId', 'Name',
            'Group', 'ParentContentTypeId', 'FieldCount', 'FieldTypes',
            'DocumentTemplateUrl', 'Hidden', 'ReadOnly', 'Sealed'
        )
        if ($ContentTypes.Count -gt 0) {
            $ContentTypes | Select-Object -Property $columns |
                ConvertTo-SPSCsvSafeRecord |
                Export-Csv -Path $contentTypesCsvPath -NoTypeInformation -Encoding UTF8
        }
        else {
            Set-Content -Path $contentTypesCsvPath -Value ('"' + ($columns -join '","') + '"') -Encoding UTF8
        }
        ConvertTo-Json -InputObject @($ContentTypes) -Depth 6 |
            Set-Content -Path $contentTypesJsonPath -Encoding UTF8
    }

    $managedMetadataCsvPath = $null
    $managedMetadataJsonPath = $null
    if ($PSBoundParameters.ContainsKey('ManagedMetadataLists')) {
        $htmlParams['ManagedMetadataLists'] = @($ManagedMetadataLists)
        $managedMetadataCsvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-managedmetadata-{1}.csv' -f $BaseName, $timestamp)
        $managedMetadataJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-managedmetadata-{1}.json' -f $BaseName, $timestamp)
        $managedMetadataColumns = @(
            'SiteUrl', 'WebUrl', 'ListTitle', 'ListUrl', 'ListTemplate', 'ListType',
            'ListItemCount', 'ItemLastModifiedDate', 'ManagedMetadataColumnCount',
            'ManagedMetadataColumns', 'TermSetIds'
        )
        if ($ManagedMetadataLists.Count -gt 0) {
            $ManagedMetadataLists | Select-Object -Property $managedMetadataColumns |
                ConvertTo-SPSCsvSafeRecord |
                Export-Csv -Path $managedMetadataCsvPath -NoTypeInformation -Encoding UTF8
        }
        else {
            Set-Content -Path $managedMetadataCsvPath -Value ('"' + ($managedMetadataColumns -join '","') + '"') -Encoding UTF8
        }
        ConvertTo-Json -InputObject @($ManagedMetadataLists) -Depth 6 |
            Set-Content -Path $managedMetadataJsonPath -Encoding UTF8
    }

    $externalListsCsvPath = $null
    $externalListsJsonPath = $null
    if ($PSBoundParameters.ContainsKey('ExternalLists')) {
        $htmlParams['ExternalLists'] = @($ExternalLists)
        $externalListsCsvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-externallists-{1}.csv' -f $BaseName, $timestamp)
        $externalListsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-externallists-{1}.json' -f $BaseName, $timestamp)
        $externalListColumns = @(
            'SiteUrl', 'WebUrl', 'ListTitle', 'ListUrl', 'LobSystemInstance', 'EntityNamespace', 'Entity'
        )
        if ($ExternalLists.Count -gt 0) {
            $ExternalLists | Select-Object -Property $externalListColumns |
                ConvertTo-SPSCsvSafeRecord |
                Export-Csv -Path $externalListsCsvPath -NoTypeInformation -Encoding UTF8
        }
        else {
            Set-Content -Path $externalListsCsvPath -Value ('"' + ($externalListColumns -join '","') + '"') -Encoding UTF8
        }
        ConvertTo-Json -InputObject @($ExternalLists) -Depth 6 |
            Set-Content -Path $externalListsJsonPath -Encoding UTF8
    }

    $sharePointAlertsCsvPath = $null
    $sharePointAlertsJsonPath = $null
    if ($PSBoundParameters.ContainsKey('SharePointAlerts')) {
        $sharePointAlertsCsvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-sharepointalerts-{1}.csv' -f $BaseName, $timestamp)
        $sharePointAlertsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-sharepointalerts-{1}.json' -f $BaseName, $timestamp)
        $sharePointAlertColumns = @(
            'SiteUrl', 'WebUrl', 'AlertId', 'Title', 'AlertTemplateName', 'AlertType', 'ListUrl', 'ListId',
            'ItemId', 'EventType', 'AlertFrequency', 'AlertTime', 'Status', 'DeliveryChannels', 'AlwaysNotify',
            'DynamicRecipient', 'Filter', 'UserId', 'UserLoginName'
        )
        if ($SharePointAlerts.Count -gt 0) {
            $SharePointAlerts | Select-Object -Property $sharePointAlertColumns |
                ConvertTo-SPSCsvSafeRecord |
                Export-Csv -Path $sharePointAlertsCsvPath -NoTypeInformation -Encoding UTF8
        }
        else {
            Set-Content -Path $sharePointAlertsCsvPath -Value ('"' + ($sharePointAlertColumns -join '","') + '"') -Encoding UTF8
        }
        ConvertTo-Json -InputObject @($SharePointAlerts) -Depth 6 |
            Set-Content -Path $sharePointAlertsJsonPath -Encoding UTF8
    }

    $bcsCsvPath = $null
    $bcsJsonPath = $null
    if ($PSBoundParameters.ContainsKey('BcsApplications')) {
        $htmlParams['BcsApplications'] = @($BcsApplications)
        $htmlParams['BcsInventoryComplete'] = $BcsInventoryComplete
        $bcsCsvPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-bcs-{1}.csv' -f $BaseName, $timestamp)
        $bcsJsonPath = Join-Path -Path $OutputFolder -ChildPath ('{0}-bcs-{1}.json' -f $BaseName, $timestamp)
        $bcsColumns = @(
            'WebApplicationUrls', 'BdcServiceApplicationId', 'LobSystemName', 'LobSystemType',
            'LobSystemInstances', 'EntityCount', 'LobEntities'
        )
        if ($BcsApplications.Count -gt 0) {
            $BcsApplications | Select-Object -Property $bcsColumns |
                ConvertTo-SPSCsvSafeRecord |
                Export-Csv -Path $bcsCsvPath -NoTypeInformation -Encoding UTF8
        }
        else {
            Set-Content -Path $bcsCsvPath -Value ('"' + ($bcsColumns -join '","') + '"') -Encoding UTF8
        }
        ConvertTo-Json -InputObject @($BcsApplications) -Depth 6 |
            Set-Content -Path $bcsJsonPath -Encoding UTF8
    }

    $html = ConvertTo-SPSInventoryHtml @htmlParams
    $html | Set-Content -Path $htmlPath -Encoding UTF8

    $totalSizeGb = 0.0
    foreach ($record in $siteRecords) {
        if ($null -ne $record.SizeGB) {
            try {
                $totalSizeGb += [double]$record.SizeGB
            }
            catch {
                continue
            }
        }
    }

    $manifest = [PSCustomObject]@{
        ReportPackVersion = '1.0'
        GeneratedOn = (Get-Date).ToString('o')
        BaseName = $BaseName
        Timestamp = $timestamp
        Summary = [PSCustomObject]@{
            TotalRecords = @($records).Count
            SiteCollections = @($siteRecords).Count
            WebApplicationFailures = @($records | Where-Object { $_.InventoryScope -eq 'WebApplication' }).Count
            PartialAssessments = @($siteRecords | Where-Object { $_.AssessmentStatus -eq 'Partial' }).Count
            FailedAssessments = @($siteRecords | Where-Object { $_.AssessmentStatus -eq 'Failed' }).Count
            TotalContentGB = [math]::Round($totalSizeGb, 4)
            AlertCount = @($alerts).Count
            ExcludedPersonalSites = $ExcludedPersonalSiteCount
            ExcludedSiteMasters = $ExcludedSiteMasterCount
            BcsInventoryComplete = if ($PSBoundParameters.ContainsKey('BcsApplications')) { $BcsInventoryComplete } else { $null }
        }
        Files = [PSCustomObject]@{
            InventoryCsv = $csvPath
            InventoryJson = $jsonPath
            InventoryHtml = $htmlPath
            SitesJson = $sitesJsonPath
            AuthJson = $authJsonPath
            WorkflowsJson = $workflowsJsonPath
            AppsJson = $appsJsonPath
            PublishingJson = $publishingJsonPath
            PermissionsJson = $permissionsJsonPath
            IrmLocksJson = $irmLocksJsonPath
            LargeContentJson = $largeContentJsonPath
            AlertsJson = $alertsJsonPath
            AlertsCsv = $alertsCsvPath
            ContentTypesCsv = $contentTypesCsvPath
            ContentTypesJson = $contentTypesJsonPath
            ManagedMetadataCsv = $managedMetadataCsvPath
            ManagedMetadataJson = $managedMetadataJsonPath
            ExternalListsCsv = $externalListsCsvPath
            ExternalListsJson = $externalListsJsonPath
            SharePointAlertsCsv = $sharePointAlertsCsvPath
            SharePointAlertsJson = $sharePointAlertsJsonPath
            BcsCsv = $bcsCsvPath
            BcsJson = $bcsJsonPath
            SolutionsJson = if ($SolutionJsonPath) { $SolutionJsonPath } else { $null }
        }
    }
    ConvertTo-Json -InputObject $manifest -Depth 6 | Set-Content -Path $manifestJsonPath -Encoding UTF8

    return [PSCustomObject]@{
        CsvPath  = $csvPath
        JsonPath = $jsonPath
        HtmlPath = $htmlPath
        SitesJsonPath = $sitesJsonPath
        AuthJsonPath = $authJsonPath
        WorkflowsJsonPath = $workflowsJsonPath
        AppsJsonPath = $appsJsonPath
        PublishingJsonPath = $publishingJsonPath
        PermissionsJsonPath = $permissionsJsonPath
        IrmLocksJsonPath = $irmLocksJsonPath
        LargeContentJsonPath = $largeContentJsonPath
        AlertsJsonPath = $alertsJsonPath
        AlertsCsvPath = $alertsCsvPath
        ManifestJsonPath = $manifestJsonPath
        ContentTypesCsvPath = $contentTypesCsvPath
        ContentTypesJsonPath = $contentTypesJsonPath
        ManagedMetadataCsvPath = $managedMetadataCsvPath
        ManagedMetadataJsonPath = $managedMetadataJsonPath
        ExternalListsCsvPath = $externalListsCsvPath
        ExternalListsJsonPath = $externalListsJsonPath
        SharePointAlertsCsvPath = $sharePointAlertsCsvPath
        SharePointAlertsJsonPath = $sharePointAlertsJsonPath
        BcsCsvPath = $bcsCsvPath
        BcsJsonPath = $bcsJsonPath
    }
}
